// Generates src/kit/fonts.generated.ts: a single TS module exporting a CSS
// string with the brand's fonts base64-embedded as @font-face rules.
//
// Why base64-embed instead of self-hosting via staticFile() + @remotion/
// fonts' loadFont() (or @remotion/google-fonts): those still fetch at render
// time and depend on delayRender()/continueRender() resolving correctly
// across every browser tab Remotion recycles during a long render. In
// resource-constrained/sandboxed environments that reproducibly hung on a
// tab-recycle boundary mid-render. Embedding the font as a data: URI in
// inline CSS removes the fetch entirely — the browser parses it
// synchronously from a string already in the page, so there's nothing to
// hang on, in any environment.
//
// Trade-off: src/kit/fonts.generated.ts is checked into git, since regenerating
// it requires the @fontsource packages to be installed.
//
// To change fonts: `npm i @fontsource/<font>`, edit FONTS below and FONT in
// src/kit/theme.ts, then run `npm run fonts`.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const FONTS = [
  { family: "Space Grotesk", weight: "500", pkg: "@fontsource/space-grotesk", file: "space-grotesk-latin-500-normal.woff2" },
  { family: "Space Grotesk", weight: "700", pkg: "@fontsource/space-grotesk", file: "space-grotesk-latin-700-normal.woff2" },
  { family: "JetBrains Mono", weight: "500", pkg: "@fontsource/jetbrains-mono", file: "jetbrains-mono-latin-500-normal.woff2" },
  { family: "JetBrains Mono", weight: "700", pkg: "@fontsource/jetbrains-mono", file: "jetbrains-mono-latin-700-normal.woff2" },
];

let css = "";
let ok = 0;
for (const f of FONTS) {
  const src = join(root, "node_modules", f.pkg, "files", f.file);
  if (!existsSync(src)) {
    console.warn(`[fonts] skipped ${f.pkg}/files/${f.file} — not found (is ${f.pkg} installed?)`);
    continue;
  }
  const b64 = readFileSync(src).toString("base64");
  css += `@font-face { font-family: '${f.family}'; font-weight: ${f.weight}; font-style: normal; font-display: block; src: url(data:font/woff2;base64,${b64}) format('woff2'); }\n`;
  ok++;
}

const target = join(root, "src", "kit", "fonts.generated.ts");
if (ok === 0 && existsSync(target)) {
  // Don't clobber a working checked-in file with an empty one (e.g. a
  // render-only environment where the @fontsource packages are missing).
  console.warn("[fonts] no font files found — keeping existing src/kit/fonts.generated.ts");
} else {
  const out = `// AUTO-GENERATED by scripts/generate-fonts.mjs — do not edit by hand.
// Regenerate with \`npm run fonts\` after changing the FONTS list there.
export const FONT_FACE_CSS = ${JSON.stringify(css)};
`;
  writeFileSync(target, out);
  console.log(`[fonts] embedded ${ok}/${FONTS.length} fonts into src/kit/fonts.generated.ts`);
}
